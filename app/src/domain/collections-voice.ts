/**
 * Collections voice scripts + agent persona (SAU-334, WS-3) — the SERVER-FIXED half
 * of the outbound voice loop. "The rules ARE the product" (SAU-332): the two pieces
 * of speech that regulation pins down are constants HERE, not prompt text the model
 * can improvise away.
 *
 *   • Guardrail 5 — required disclosure ("mini-Miranda"). FDCPA §1692e(11): every
 *     communication must disclose it is from a debt collector attempting to collect a
 *     debt. {@link COLLECTIONS_REQUIRED_DISCLOSURE} is the fixed text the dialer injects
 *     as the FIRST utterance of every connected call — never generated by the model.
 *
 *   • Guardrail 8 — limited-content voicemail. Reg-F §1006.2(j) / §1006.6(d) define a
 *     "limited-content message": a voicemail may include only the consumer's name, the
 *     fact that the caller hopes to be called back, a callback number and the caller's
 *     name(s) — and MUST NOT state that the consumer owes a debt or reveal the balance.
 *     {@link buildVoicemailScript} produces exactly that, and {@link assertNoDebtDetails}
 *     is the defensive check the dialer runs before any voicemail is left.
 *
 * Everything here is PURE and PII-free by construction: the only inputs are the agency
 * name and a callback number (the agency's own number, not the debtor's). No debt
 * amount, balance, account number, or "you owe" language is permitted in the voicemail.
 *
 * Scope: synthetic POC (SAU-328). Nothing here places a call.
 */

/**
 * Guardrail 5 — the fixed mini-Miranda disclosure. Injected verbatim by the dialer as
 * the opening line of EVERY connected call (asserted in WS-3 tests), so the disclosure
 * can never be dropped, paraphrased, or delayed by the model. Combines the FDCPA
 * §1692e(11) "debt collector / attempt to collect" disclosure with the call-recording
 * notice we apply uniformly.
 */
export const COLLECTIONS_REQUIRED_DISCLOSURE =
  'This is an attempt to collect a debt, and any information obtained will be used for that purpose. ' +
  'This communication is from a debt collector. This call may be monitored or recorded.';

/** Non-PII inputs for the limited-content voicemail (guardrail 8). */
export interface VoicemailScriptInput {
  /** The collection agency / caller's name. NOT the debtor's name (no PII). */
  agencyName: string;
  /** A callback number for the agency (E.164 or formatted). NOT the debtor's number. */
  callbackNumber: string;
  /**
   * Optional consumer FIRST name only — Reg-F permits naming the consumer in a
   * limited-content message. Omit it (the default) to keep the script fully PII-free.
   */
  consumerFirstName?: string;
}

/**
 * Guardrail 8 — build the limited-content voicemail. Contains ONLY: (optionally) the
 * consumer's first name, a request for a callback, the agency name, and a callback
 * number. It deliberately does NOT say the consumer owes a debt and carries no balance,
 * account number, or amount — those would make it a non-limited "communication" that
 * may not be left where a third party could overhear (Reg-F §1006.6(d)(2)).
 */
export function buildVoicemailScript(input: VoicemailScriptInput): string {
  const greeting = input.consumerFirstName ? `Hello ${input.consumerFirstName}. ` : 'Hello. ';
  return (
    `${greeting}This is a message from ${input.agencyName}. ` +
    `This is not a sales call. Please call us back at ${input.callbackNumber}. ` +
    `Again, that number is ${input.callbackNumber}. Thank you.`
  );
}

/**
 * Tokens that would turn a limited-content voicemail into a disclosing communication
 * (it states/implies a debt) — none of these may appear in a voicemail script.
 */
const DEBT_DETAIL_PATTERNS: RegExp[] = [
  /\bdebt\b/i,
  /\bowe[sd]?\b/i,
  /\bbalance\b/i,
  /\bamount\b/i,
  /\baccount\s*(?:number|#|no\.?)\b/i,
  /\bcollect(?:ion|ing)?\b/i,
  /\bpast[-\s]?due\b/i,
  /\bpayment\b/i,
  /\$\s*\d/, // any dollar figure
  /\b\d+\s*(?:dollars|cents)\b/i,
];

/** Result of screening a voicemail script for prohibited debt details. */
export interface DebtDetailScreen {
  ok: boolean;
  /** The matched prohibited tokens, if any (for the audit/log — they are NOT PII). */
  violations: string[];
}

/** Screen a voicemail script for any prohibited debt detail (guardrail 8). */
export function screenVoicemailForDebtDetails(script: string): DebtDetailScreen {
  const violations: string[] = [];
  for (const re of DEBT_DETAIL_PATTERNS) {
    const m = script.match(re);
    if (m) violations.push(m[0]);
  }
  return { ok: violations.length === 0, violations };
}

/**
 * Fail-closed assertion the dialer runs before leaving any voicemail: throws if the
 * script contains debt details. A misbuilt script can never reach a real voicemail.
 */
export function assertNoDebtDetails(script: string): void {
  const screen = screenVoicemailForDebtDetails(script);
  if (!screen.ok) {
    throw new Error(
      `Voicemail script contains prohibited debt details (guardrail 8): ${screen.violations.join(', ')}`,
    );
  }
}

/** Inputs for the collections agent persona instructions. */
export interface AgentInstructionsInput {
  agencyName: string;
  /** The fixed disclosure to mandate as the opening line (defaults to the constant). */
  disclosure?: string;
}

/**
 * Build the realtime voice persona for the collections agent: professional, calm, and
 * NON-HARASSING. The hard rules (calling windows, frequency, opt-out) are enforced by
 * the WS-1 engine and the dialer, not the prompt — but the persona reinforces the
 * conduct rules a model controls turn-to-turn (tone, no threats, immediate compliance
 * with cease/opt-out requests). The disclosure is ALSO injected server-side as the
 * first utterance; restating it here is belt-and-suspenders, not the guarantee.
 */
export function buildCollectionsAgentInstructions(input: AgentInstructionsInput): string {
  const disclosure = input.disclosure ?? COLLECTIONS_REQUIRED_DISCLOSURE;
  return [
    `You are a professional, courteous collections representative for ${input.agencyName}.`,
    `Your opening line has ALREADY been delivered for you: "${disclosure}" — do not repeat it unless asked.`,
    'Conduct rules you must always follow:',
    '- Be calm, respectful, and professional. Never raise your voice, threaten, intimidate, or use abusive or deceptive language.',
    '- Never threaten arrest, legal action you are not authorized to take, or any consequence that is not true.',
    '- Do not discuss the debt with anyone other than the consumer; do not reveal debt details to third parties.',
    '- If the person asks you to stop calling, says this is a bad time, or disputes the debt, acknowledge it politely and tell them it will be honored. Do not argue.',
    '- If asked, provide the agency name and a callback number. Offer to answer questions and discuss options without pressure.',
    '- Keep the call brief and on-topic. If the consumer is unavailable, end politely; the system will handle any voicemail.',
  ].join('\n');
}
